const DICTS: Record<Lang, Record<Key, string>> = { en, ar };

export type I18nKey = Key;

export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  return DICTS[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function dir(lang: Lang): "rtl" | "ltr" {
  return lang === "ar" ? "rtl" : "ltr";
}

export function isI18nKey(key: string): key is Key {
  return key in en;
}
